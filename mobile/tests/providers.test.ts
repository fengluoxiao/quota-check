import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash, createHmac } from 'node:crypto';
import {
  parseProvider,
  queryService,
  serviceRequest,
  signVolc,
  HashFunctions,
} from '../src/providers';
import { SERVICES, ServiceId, ServiceProfile, validateService } from '../src/serviceCatalog';
import { validateVault, lockImported, exportOwned } from '../src/models';
const cases = JSON.parse(
  readFileSync(new URL('../../tests/fixtures/providers-usage.json', import.meta.url), 'utf8'),
) as {
  id: ServiceId;
  payload: unknown;
  expect: { used: number | null; remaining: number | null; title: string; contains?: string }[];
}[];
const hash: HashFunctions = {
  sha256: (value) => createHash('sha256').update(value).digest('hex'),
  hmacSHA256: (keyHex, message) =>
    createHmac('sha256', Buffer.from(keyHex, 'hex')).update(message).digest('hex'),
};
function profile(id: ServiceId): ServiceProfile {
  const spec = SERVICES.find((s) => s.id === id)!;
  return validateService(id, {
    ...Object.fromEntries(
      spec.fields.map((f) => [
        f.key,
        spec.auth === 'cookie' && f.key === 'secret'
          ? 'ssoSessionId=test-only; tenantToken=test-only'
          : 'test-only-secret',
      ]),
    ),
    sealed: false,
  });
}
for (const c of cases)
  test('Provider protocol: ' + c.id, () => {
    const rows = parseProvider(c.id, c.payload);
    assert.equal(rows.length, c.expect.length);
    rows.forEach((r, i) => {
      const e = c.expect[i]!;
      assert.equal(r.used, e.used);
      assert.equal(r.remaining, e.remaining);
      assert.ok(r.title.includes(e.title));
      if (e.contains) assert.ok(r.details.includes(e.contains));
    });
  });
test('Console responses never leak account keys, phone numbers, or imported seat names', () => {
  for (const c of cases) {
    const text = JSON.stringify(parseProvider(c.id, c.payload, true));
    for (const secret of [
      'must-not-be-exposed-key',
      'must-not-be-exposed-secret',
      'private-seat-name',
      'private-user-phone',
    ])
      assert.ok(!text.includes(secret));
  }
});
test('Missing quota stays unknown and negative balance is preserved', () => {
  for (const c of cases) assert.throws(() => parseProvider(c.id, {}));
  const rows = parseProvider('ark_agent', { Result: { AFPFiveHour: { Quota: 100 } } });
  assert.equal(rows[0]!.used, null);
  assert.equal(rows[0]!.remaining, null);
  assert.ok(
    parseProvider('deepseek', {
      balance_infos: [{ currency: 'CNY', total_balance: '-1.25' }],
    })[0]!.details.includes('-1.25 CNY'),
  );
});
test('Provider requests use pinned read endpoints and the required authentication', () => {
  for (const s of SERVICES) {
    const r = serviceRequest(s.id, profile(s.id), 0, hash, '20261117T010203Z');
    assert.ok(r.url.startsWith('https://'));
    assert.ok(!/messages|completions|purchase|refresh-key/.test(r.url));
    if (s.auth === 'cookie') assert.equal(r.headers.Cookie, profile(s.id).secret);
    if (s.auth === 'ali') {
      const body = new URLSearchParams(r.body);
      const params = JSON.parse(body.get('params')!);
      assert.equal(params.Data.cornerstoneParam.protocol, 'V2');
      assert.equal(r.headers.Authorization, 'Bearer test-only-secret');
    }
  }
});
test('Volcengine V4 signature matches a vector generated by the official Python SDK', () => {
  const fixture = JSON.parse(
    readFileSync(new URL('../../tests/fixtures/volc-signature.json', import.meta.url), 'utf8'),
  );
  const headers = signVolc(
    {
      secret: 'AKIDEXAMPLE',
      secret2: 'test-only-secret-key',
      session_token: 'test-only-session',
      sealed: false,
    },
    hash,
    fixture.timestamp,
  );
  assert.deepEqual(headers, fixture.headers);
  assert.equal(headers['X-Security-Token'], 'test-only-session');
});
test('All provider credentials roundtrip validation and imported profiles cannot be exported', () => {
  const v = validateVault({
    version: 1,
    source: 9,
    profiles: Object.fromEntries(SERVICES.map((s) => [s.id, profile(s.id)])),
  });
  assert.equal(v.source, 9);
  assert.equal(Object.keys(v.profiles).length, SERVICES.length);
  assert.throws(() => exportOwned(lockImported(v)));
  for (const s of SERVICES) {
    assert.throws(() =>
      validateService(s.id, { ...profile(s.id), url: 'https://attacker.invalid' }),
    );
    assert.throws(() =>
      validateService(s.id, { ...profile(s.id), secret: 'test\r\nAuthorization: injected' }),
    );
  }
});
test('HTTP errors never echo raw backend messages or secrets', async () => {
  for (const status of [301, 401, 403, 429, 500])
    await assert.rejects(
      queryService('deepseek', profile('deepseek'), async () => ({
        status,
        body: 'test-private-secret',
      })),
      (e) => e instanceof Error && !e.message.includes('test-private-secret'),
    );
});
test('Astron reads all seat pages and tolerates an empty final page', async () => {
  const calls: string[] = [];
  const cards = await queryService('astron', profile('astron'), async (r) => {
    calls.push(r.url);
    const seats =
      calls.length === 1
        ? Array.from({ length: 100 }, (_, i) => ({
            id: i,
            usage: { usedPoints: i, totalAuthorizedPoints: 1000 },
          }))
        : [];
    return { status: 200, body: JSON.stringify({ code: 0, data: { seats } }) };
  });
  assert.equal(cards.length, 100);
  assert.equal(calls.length, 2);
  assert.ok(calls[0]!.includes('page=0'));
  assert.ok(calls[1]!.includes('page=1'));
});
test('Every provider query returns only normalized cards, with balances explicitly marked', async () => {
  for (const c of cases) {
    const cards = await queryService(
      c.id,
      profile(c.id),
      async () => ({ status: 200, body: JSON.stringify(c.payload) }),
      hash,
    );
    assert.equal(cards.length, c.expect.length);
    if (c.id === 'deepseek' || c.id === 'mimo_balance') assert.equal(cards[0]!.kind, 'balance');
    assert.ok(!JSON.stringify(cards).includes('must-not-be-exposed'));
  }
});

test('Nested console failure markers cannot be mistaken for free quota', () => {
  for (const failure of [
    { successResponse: false },
    { failed: true },
    { ret: ['FAIL_SYS_SESSION_EXPIRED::expired'] },
  ])
    assert.throws(() =>
      parseProvider('aliyun_token', {
        data: { DataV2: { ...failure, data: { data: { per1MonthPercentage: 0 } } } },
      }),
    );
});
